impl Palette {
    pub(in crate::tui) fn swatch(self) -> [Color; 6] {
        [
            self.accent,
            self.status_model,
            self.link,
            self.added,
            self.removed,
            self.md_strong,
        ]
    }
}

pub(in crate::tui) const fn palette_for(theme: Theme) -> &'static Palette {
    match theme {
        Theme::Default => &classic::DEFAULT,
        Theme::TokyoNight => &classic::TOKYO_NIGHT,
        Theme::Catppuccin => &classic::CATPPUCCIN,
        Theme::Dracula => &classic::DRACULA,
        Theme::Nord => &classic::NORD,
        Theme::Gruvbox => &classic::GRUVBOX,
        Theme::SolarizedLight => &classic::SOLARIZED_LIGHT,
        Theme::OneDark => &dark::ONE_DARK,
        Theme::SolarizedDark => &dark::SOLARIZED_DARK,
        Theme::Monokai => &dark::MONOKAI,
        Theme::RosePine => &dark::ROSE_PINE,
        Theme::Kanagawa => &dark::KANAGAWA,
        Theme::Everforest => &dark::EVERFOREST,
        Theme::RosePineDawn => &extended::ROSE_PINE_DAWN,
        Theme::GruvboxLight => &extended::GRUVBOX_LIGHT,
        Theme::CatppuccinLatte => &extended::CATPPUCCIN_LATTE,
        Theme::GitHubDark => &extended::GITHUB_DARK,
        Theme::GitHubLight => &extended::GITHUB_LIGHT,
        Theme::AyuDark => &extended::AYU_DARK,
        Theme::NightOwl => &extended::NIGHT_OWL,
    }
}
